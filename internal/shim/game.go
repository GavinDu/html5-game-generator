// Package shim builds the generated game code. The stub template emits a
// complete, valid GameShim v1 game; the real codegen LLM replaces this
// builder while targeting the same contract.
package shim

import (
	"fmt"

	"doodlequest/internal/model"
)

// BuildGameJS returns a complete tap-to-collect game starring the first
// element's sprite. It obeys the shim hard rules: no network, no eval,
// single input verb, Shim.end is always reachable.
func BuildGameJS(doc *model.DesignDoc, playerSpriteID string) string {
	title := doc.Title
	if title == "" {
		title = "DoodleQuest"
	}
	return fmt.Sprintf(`// %s — generated by DoodleQuest (stub codegen)
Shim.init({ width: 390, height: 844, background: '#1b2340' });

var player = Shim.sprite('%s', { x: 195, y: 700, w: 72, h: 72 });
var stars = [];
var score = 0;
var elapsed = 0;
var spawnT = 0;

Shim.audio.music('audio/theme.wav', { loop: true, volume: 0.6 });

Shim.input('tap', function (x, y) {
  player.x = Math.max(36, Math.min(354, x));
});

Shim.text('score', 'Score: 0', { x: 16, y: 16, size: 28, color: '#ffffff' });
Shim.text('title', '%s', { x: 16, y: 52, size: 18, color: '#9fb2ff' });

Shim.loop(function (dt) {
  elapsed += dt;
  spawnT += dt;
  if (spawnT > 0.7) {
    spawnT = 0;
    stars.push(Shim.sprite('star', { x: 24 + Math.random() * 342, y: -24, w: 40, h: 40 }));
  }
  for (var i = stars.length - 1; i >= 0; i--) {
    var s = stars[i];
    s.y += 170 * dt;
    var dx = s.x - player.x;
    var dy = s.y - player.y;
    if (dx * dx + dy * dy < 2700) {
      stars.splice(i, 1);
      score += 1;
      Shim.text('score', 'Score: ' + score, { x: 16, y: 16, size: 28, color: '#ffffff' });
      Shim.audio.tone({ freq: 660 + score * 20, dur: 0.12, type: 'sine' });
    } else if (s.y > 880) {
      stars.splice(i, 1);
    }
  }
  if (score >= 10) {
    Shim.end({ score: score, won: true, stats: { time_s: Math.round(elapsed) } });
  }
});
`, title, playerSpriteID, title)
}
